(ns gen
  "Rebuild the files that list every demo (`bb gen`).

  demos.edn is the list, edited by hand. From it and the demo directories this
  writes:

  - bb.edn, between its BEGIN/END markers         one task per demo
  - docs/guide/demos.md                           the site's gallery

  Each demo directory, its project.clj, its docs page and its recordings are
  hand-owned. gen only reads them, and fails when a demo directory and
  demos.edn disagree.

  Usage: bb gen [--check]
  --check writes nothing and exits 1 if any of those files is out of date."
  (:require
   [babashka.fs :as fs]
   [clojure.edn :as edn]
   [clojure.string :as str]))

(def root (str (fs/parent (fs/parent (fs/absolutize *file*)))))

(def repo-url "https://github.com/b12n-oss/raylib-jank-demo")

;; The hand-written tasks in bb.edn. A demo with one of these names gets no task
;; of its own, though `bb run <demo>` still reaches it.
(def fixed-tasks #{"info" "list" "run" "run-all" "check" "lint" "lint:strict" "doctor" "gen"
                   "clean" "record" "sync-recordings" "demos:examples"})

(def begin-marker "  ;; BEGIN per-demo tasks, generated by `bb gen`\n")
(def end-marker "  ;; END per-demo tasks\n")

(defn- ->file [name] (str (str/replace name "-" "_") ".jank"))

(defn- demo-dirs
  "Every directory here holding a demo: a project.clj and its scene source."
  []
  (sort (for [d (fs/list-dir root)
              :let [name (str (fs/file-name d))]
              :when (and (fs/exists? (fs/file d "project.clj"))
                         (fs/exists? (fs/file d "src/net/b12n/raylib_jnk/scenes" (->file name))))]
          name)))

(defn- media-of
  "The demo's recording under docs/demos, gif preferred, or nil."
  [name]
  (first (for [ext ["gif" "png"]
               :when (fs/exists? (fs/file root "docs/demos" (str name "." ext)))]
           (str name "." ext))))

(defn- bb-edn-with-tasks
  "bb.edn's text with the block between the markers replaced, or nil when the
  markers are missing."
  [text entries]
  (let [b (str/index-of text begin-marker)
        e (some-> b (->> (str/index-of text end-marker)))]
    (when (and b e)
      (let [named (remove (comp fixed-tasks :name) entries)
            w (apply max (map (comp count :name) named))]
        (str (subs text 0 (+ b (count begin-marker)))
             (str/join (for [{:keys [name desc]} named]
                         (str "  " (format (str "%-" w "s") name)
                              " {:doc " (pr-str (str "▶ " (or desc name)))
                              " :task (exit-with (run-demo " (pr-str name) "))}\n")))
             (subs text e))))))

(defn- gallery-md [entries]
  (str "<!-- Generated by `bb gen` from demos.edn. Edits here are overwritten. -->\n"
       "# Demo gallery\n"
       "\n"
       "All " (count entries) " demos, grouped by category. Each name links to the demo's\n"
       "own sub-project, where its page has the full description and source.\n"
       (str/join
        (for [[category ds] (sort-by key (group-by (fn [e] (or (:category e) "local")) entries))]
          (str "\n## " category " (" (count ds) ")\n"
               (str/join
                (for [{:keys [name desc controls]} ds]
                  (str "\n### [" name "](" repo-url "/tree/main/" name ")\n\n"
                       (when desc (str desc ". "))
                       (when (seq controls) (str "Controls: " controls ". "))
                       "Run it with `bb " (if (fixed-tasks name) (str "run " name) name) "`.\n\n"
                       (when-let [m (media-of name)] (str "![" name "](../demos/" m ")\n"))))))))))

(defn- fail! [& msg]
  (binding [*out* *err*] (println (apply str msg)))
  (System/exit 1))

(defn -main [& args]
  (let [check? (some #{"--check"} args)
        entries (sort-by :name (edn/read-string (slurp (fs/file root "demos.edn"))))
        listed (set (map :name entries))
        on-disk (set (demo-dirs))
        bb-edn (fs/file root "bb.edn")
        bb-text (bb-edn-with-tasks (slurp bb-edn) entries)
        outputs [[bb-edn bb-text]
                 [(fs/file root "docs/guide/demos.md") (gallery-md entries)]]]
    (when-let [missing (seq (sort (remove on-disk listed)))]
      (fail! "In demos.edn with no demo directory: " (str/join " " missing)))
    (when-let [unlisted (seq (sort (remove listed on-disk)))]
      (fail! "Demo directories missing from demos.edn: " (str/join " " unlisted)))
    (when-not bb-text
      (fail! "bb.edn has lost its BEGIN/END per-demo task markers"))
    (when-let [clash (seq (filter fixed-tasks listed))]
      (println "No task of their own (name taken by a bb.edn task):" (str/join " " clash)))
    (let [stale (for [[f content] outputs
                      :when (not= content (when (fs/exists? f) (slurp f)))]
                  [f content])]
      (doseq [[f content] stale]
        (println (if check? "out of date:" "updated:") (str (fs/relativize root f)))
        (when-not check?
          (fs/create-dirs (fs/parent f))
          (spit f content)))
      (println (str (count entries) " demos, " (count stale) " file(s) "
                    (if check? "out of date" "changed")))
      (when (and check? (seq stale))
        (fail! "Run `bb gen` and commit the result.")))))

(when (= *file* (System/getProperty "babashka.file"))
  (apply -main *command-line-args*))
